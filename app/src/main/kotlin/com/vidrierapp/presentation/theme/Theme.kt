@Composable
fun VidrierAppTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme

    val dimmedColors = if (darkTheme) DarkDimmedColors else LightDimmedColors

    CompositionLocalProvider(LocalDimmedColors provides dimmedColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content
        )
    }
}
